-- Solicitudes de inscripcion con revision privada de administracion.
-- Si cambia el correo administrador, actualiza las politicas de este archivo
-- y ADMIN_EMAIL en script.js para que coincidan.

create table if not exists public.inscripciones (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references public.perfiles(id) on delete cascade,
  curso text not null check (curso in (
    'Fotografía & Edición de Fotos',
    'Efectos Visuales VFX',
    'Colorización & Color Grading',
    'Motion Graphics',
    'Audio Profesional para Vídeo',
    'Edición Avanzada & Workflow'
  )),
  estado text not null default 'pendiente'
    check (estado in ('pendiente', 'aceptada', 'rechazada')),
  solicitado_en timestamptz not null default now(),
  revisado_en timestamptz,
  revisado_por uuid references auth.users(id)
);

create index if not exists inscripciones_usuario_fecha_idx
  on public.inscripciones (usuario_id, solicitado_en desc);

create unique index if not exists inscripciones_curso_activo_unico_idx
  on public.inscripciones (usuario_id, curso)
  where estado in ('pendiente', 'aceptada');

alter table public.inscripciones enable row level security;

drop policy if exists "inscripciones leer propias y admin" on public.inscripciones;
create policy "inscripciones leer propias y admin"
  on public.inscripciones for select to authenticated
  using (
    usuario_id = auth.uid()
    or lower(coalesce(auth.jwt() ->> 'email', '')) = 'caperarojasnicolassantiago@gmail.com'
  );

drop policy if exists "inscripciones crear propia pendiente" on public.inscripciones;
create policy "inscripciones crear propia pendiente"
  on public.inscripciones for insert to authenticated
  with check (usuario_id = auth.uid() and estado = 'pendiente');

drop policy if exists "admin revisar inscripciones" on public.inscripciones;
create policy "admin revisar inscripciones"
  on public.inscripciones for update to authenticated
  using (
    lower(coalesce(auth.jwt() ->> 'email', '')) = 'caperarojasnicolassantiago@gmail.com'
    and estado = 'pendiente'
  )
  with check (
    lower(coalesce(auth.jwt() ->> 'email', '')) = 'caperarojasnicolassantiago@gmail.com'
    and estado in ('aceptada', 'rechazada')
    and revisado_por = auth.uid()
    and revisado_en is not null
  );

grant select, insert, update on public.inscripciones to authenticated;
grant usage, select on sequence public.inscripciones_id_seq to authenticated;

-- Los perfiles privados siguen ocultos a estudiantes, pero el administrador
-- puede ver el nombre y correo del solicitante para revisar cada inscripción.
drop policy if exists "perfil leer" on public.perfiles;
create policy "perfil leer"
  on public.perfiles for select to anon, authenticated
  using (
    auth.uid() = id
    or es_publico = true
    or lower(coalesce(auth.jwt() ->> 'email', '')) = 'caperarojasnicolassantiago@gmail.com'
  );
